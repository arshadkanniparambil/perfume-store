/**
 * Writes supabase/seed.sql from the sample catalog, for people who prefer to
 * paste SQL into the Supabase SQL Editor instead of running `npm run db:seed`.
 * The Supabase CLI also runs this file on `supabase db reset`.
 *
 *   npm run db:seed-sql
 *
 * Like the seed script, it only inserts or updates, never deletes, and leaves
 * existing stock levels alone.
 */
import { writeFileSync } from "node:fs";
import {
  sampleBrands,
  sampleCategories,
  sampleProducts,
} from "../lib/sample-catalog.ts";

const q = (value: string) => `'${value.replaceAll("'", "''")}'`;

export function buildSeedSql(): string {
  const out: string[] = [
    "-- GENERATED by scripts/generate-seed-sql.ts from lib/sample-catalog.ts.",
    "-- Do not edit by hand; run `npm run db:seed-sql` after changing the catalog.",
    "-- Safe to run more than once. Prices are integer halalas.",
    "",
    "begin;",
    "",
    "insert into public.brands (slug, name_en, name_ar, sort_order) values",
    sampleBrands.map((b, i) => `  (${q(b.slug)}, ${q(b.name)}, ${q(b.nameAr)}, ${i})`).join(",\n"),
    "on conflict (slug) do update set name_en = excluded.name_en,",
    "  name_ar = excluded.name_ar, sort_order = excluded.sort_order;",
    "",
    "insert into public.categories (slug, name_en, name_ar, sort_order) values",
    sampleCategories.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.nameAr)}, ${i})`).join(",\n"),
    "on conflict (slug) do update set name_en = excluded.name_en,",
    "  name_ar = excluded.name_ar, sort_order = excluded.sort_order;",
  ];

  for (const [index, p] of sampleProducts.entries()) {
    out.push(
      "",
      `-- ${p.brand} ${p.name}`,
      "insert into public.products (brand_id, slug, name_en, name_ar,",
      "  description_en, description_ar, concentration, notes_top_en,",
      "  notes_heart_en, notes_base_en, notes_top_ar, notes_heart_ar,",
      "  notes_base_ar, accent_color, sort_order)",
      `values ((select id from public.brands where slug = ${q(p.brandSlug)}),`,
      `  ${q(p.slug)}, ${q(p.name)}, ${q(p.nameAr)},`,
      `  ${q(p.description)},`,
      `  ${q(p.descriptionAr)}, ${q(p.concentration)},`,
      `  ${q(p.notes.top)}, ${q(p.notes.heart)}, ${q(p.notes.base)},`,
      `  ${q(p.notes.topAr)}, ${q(p.notes.heartAr)}, ${q(p.notes.baseAr)},`,
      `  ${q(p.tone)}, ${index})`,
      "on conflict (slug) do update set brand_id = excluded.brand_id,",
      "  name_en = excluded.name_en, name_ar = excluded.name_ar,",
      "  description_en = excluded.description_en,",
      "  description_ar = excluded.description_ar,",
      "  concentration = excluded.concentration,",
      "  notes_top_en = excluded.notes_top_en, notes_heart_en = excluded.notes_heart_en,",
      "  notes_base_en = excluded.notes_base_en, notes_top_ar = excluded.notes_top_ar,",
      "  notes_heart_ar = excluded.notes_heart_ar, notes_base_ar = excluded.notes_base_ar,",
      "  accent_color = excluded.accent_color, sort_order = excluded.sort_order;",
      "",
      "insert into public.product_categories (product_id, category_id)",
      "select p.id, c.id from public.products p, public.categories c",
      `where p.slug = ${q(p.slug)} and c.slug in (${p.categories.map(q).join(", ")})`,
      "on conflict do nothing;",
      "",
      "insert into public.product_variants (product_id, sku, size_ml, price_halalas, sort_order)",
      "select p.id, v.sku, v.size_ml, v.price_halalas, v.sort_order",
      "from public.products p, (values",
      p.sizes.map((s, i) => `  (${q(s.sku)}, ${s.ml}, ${s.priceHalalas}, ${i})`).join(",\n"),
      ") as v (sku, size_ml, price_halalas, sort_order)",
      `where p.slug = ${q(p.slug)}`,
      "on conflict (sku) do update set product_id = excluded.product_id,",
      "  size_ml = excluded.size_ml, price_halalas = excluded.price_halalas,",
      "  sort_order = excluded.sort_order;",
      "",
      "insert into public.inventory (variant_id, quantity_on_hand)",
      "select v.id, s.stock from public.product_variants v",
      "join (values",
      p.sizes.map((s) => `  (${q(s.sku)}, ${s.stock})`).join(",\n"),
      ") as s (sku, stock) on s.sku = v.sku",
      "on conflict (variant_id) do nothing;",
    );
  }
  out.push("", "commit;", "");
  return out.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = new URL("../supabase/seed.sql", import.meta.url);
  writeFileSync(path, buildSeedSql());
  console.log("Wrote supabase/seed.sql");
}
